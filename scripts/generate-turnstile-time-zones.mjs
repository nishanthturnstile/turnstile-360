import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const pinnedNode = readFileSync('.node-version', 'utf8').trim().replace(/^v/, '');
assert.equal(process.versions.node, pinnedNode, 'Generate time zones with the pinned Node runtime');
const zones = [...new Set([...Intl.supportedValuesOf('timeZone'), 'UTC'])].sort();
const provenance = {
  version: 1,
  node: process.versions.node,
  icu: process.versions.icu,
  timeZoneData: process.versions.tz,
  unicode: process.versions.unicode,
  source: "Intl.supportedValuesOf('timeZone') plus UTC",
};
const destination = 'packages/turnstile-contracts/src/time-zones.ts';
const source = `// Generated by scripts/generate-turnstile-time-zones.mjs; do not edit.\nexport const TIME_ZONE_PROVENANCE = ${JSON.stringify(provenance)} as const;\nexport const SUPPORTED_TIME_ZONES = ${JSON.stringify(zones)} as const;\n`;
const formatted = spawnSync(
  'pnpm',
  ['exec', 'biome', 'format', `--stdin-file-path=${destination}`],
  {
    input: source,
    encoding: 'utf8',
  },
);
assert.equal(formatted.status, 0, 'Time-zone formatting failed');
if (process.argv.includes('--check')) {
  assert.equal(
    readFileSync(destination, 'utf8'),
    formatted.stdout,
    'Regenerate the shared time-zone allowlist',
  );
  console.log(`Shared time-zone list/provenance match pinned Node (${zones.length} zones).`);
} else {
  writeFileSync(destination, formatted.stdout);
  console.log(`Generated ${destination} (${zones.length} zones).`);
}
